'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const config=fs.readFileSync('nas_web/config.yaml','utf8');
const main=fs.readFileSync('nas_web/app/main.py','utf8');
const imp=fs.readFileSync('nas_web/app/google_photos_import.py','utf8');
const html=fs.readFileSync('nas_web/app/index.html','utf8');
const js=fs.readFileSync('nas_web/app/app.js','utf8');
assert.match(config,/version: "\d+\.\d+\.\d+"/);
assert.match(config,/max_import_mb: 8192/);
assert.match(config,/max_import_mb: int\(1,32768\)/);
assert.match(main,/min\(32768, int\(opts\.get\("max_import_mb", 8192\)\)\)/);
assert.match(main,/"max_takeout_bytes": _takeout_max_size\(\)/);
assert.match(main,/"takeout_storage": google_photos_import\.takeout_storage_info\(\)/);
assert.match(imp,/TAKEOUT_SPOOL_RESERVE = 512 \* 1024 \* 1024/);
assert.match(imp,/shutil\.disk_usage\(ARCHIVES\)/);
assert.match(imp,/_ensure_takeout_space\(total - offset\)/);
assert.match(imp,/_ensure_takeout_space\(total\)/);
assert.ok(html.includes('id="profileTakeoutLimits"'),'the profile must show current ZIP cap');
assert.match(js,/googleTakeoutLimitBytes=Number\(status\.max_takeout_bytes\)/);
assert.match(js,/file\.size>googleTakeoutLimitBytes/);
console.log('Large Takeout ZIP limit, HA /data free-space safeguard and profile capacity UI agree');
